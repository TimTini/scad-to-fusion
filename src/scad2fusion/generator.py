"""Validate and package source-derived IR as a standalone Fusion script."""
from dataclasses import asdict, is_dataclass
import hashlib
import json
from pathlib import Path
import re
import tempfile

from .frontend import compile_source, ScadError
from .units import infer_dimensions, fusion_expression


def json_value(value):
    if is_dataclass(value):
        return json_value(asdict(value))
    if isinstance(value, dict):
        return {key: json_value(item) for key, item in value.items()}
    if isinstance(value, (set, frozenset)):
        return [json_value(item) for item in sorted(value)]
    if isinstance(value, (tuple, list)):
        return [json_value(item) for item in value]
    return value


def _usages(node):
    dimensions = {'size': 1, 'r': 1, 'r1': 1, 'r2': 1, 'h': 1,
                  'height': 1, 'a': 0}
    if node['op'] == 'translate':
        dimensions['v'] = 1
    if node['op'] == 'scale':
        dimensions['v'] = 0
    if node['op'] == 'polygon':
        dimensions['points'] = 1
    if node['op'] == 'rotate_extrude':
        dimensions['angle'] = 0
    if node['op'] == 'polyhedron':
        dimensions['coordinate_expressions'] = 1

    def leaves(value):
        if isinstance(value, dict) and 'text' in value:
            yield value
        elif isinstance(value, list):
            for item in value:
                yield from leaves(item)

    for key, value in node['args'].items():
        if key in dimensions:
            for item in leaves(value):
                if not isinstance(item['value'], bool):
                    yield item['text'], dimensions[key]
    if node['op'] == 'for':
        for binding in node['args']['bindings']:
            for key in ('start', 'step', 'end'):
                if binding[key] is not None:
                    yield binding[key]['text'], 0
    for child in node['children']:
        yield from _usages(child)


def _ordered_parameters(parameters):
    result, visiting = [], set()

    def visit(name):
        if name in result:
            return
        if name in visiting:
            raise ValueError('Cyclic parameter dependency: ' + name)
        visiting.add(name)
        for dep in parameters[name]['deps']:
            if dep != name:
                visit(dep)
        visiting.remove(name)
        result.append(name)

    for name in parameters:
        visit(name)
    return result


def expanded_rebuild_parameters(parameters, seeds):
    result, pending = set(seeds), list(seeds)
    while pending:
        for name in parameters.get(pending.pop(), {}).get('deps', []):
            if name not in result:
                result.add(name)
                pending.append(name)
    return sorted(result)


def generate_package(source, output, overrides=None):
    source, output = Path(source), Path(output)
    if output.exists():
        raise FileExistsError('Output directory already exists; choose a new output directory: ' + str(output))
    name = output.name
    if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', name):
        raise ValueError('Output folder name must be a Python identifier, e.g. KhayBongTam')
    raw = source.read_bytes()
    program = compile_source(raw.decode('utf-8-sig'), overrides, str(source))
    data = json_value(program)
    definitions = {key: value['text'] for key, value in data['parameters'].items()}
    data['dimensions'] = infer_dimensions(definitions, list(_usages(data['geometry'])))
    data['parameter_order'] = _ordered_parameters(data['parameters'])
    data['parameter_expressions'] = {
        key: fusion_expression(value['text'], data['dimensions'], data['dimensions'][key])
        for key, value in data['parameters'].items()
    }
    data['source_name'] = source.name
    data['source_sha256'] = hashlib.sha256(raw).hexdigest()
    data['name'] = name
    # Import only after frontend validation so unsupported input has a source diagnostic.
    from .native_runtime import validate_program
    capabilities = validate_program(data)
    data['rebuild_parameters'] = expanded_rebuild_parameters(data['parameters'],
        data.get('rebuild_parameters', []) + capabilities['generation_time_transform_parameters'])
    header = '"""Generated by scad2fusion. Run in Autodesk Fusion Scripts."""\nfrom __future__ import annotations\n'
    header += 'import json\nPROGRAM = json.loads(' + repr(json.dumps(data, ensure_ascii=False)) + ')\n'
    parts = []
    for filename in ('units.py', 'planar.py', 'helical.py', 'round_recovery.py', 'native_geometry.py', 'native_runtime.py'):
        text = Path(__file__).with_name(filename).read_text(encoding='utf-8')
        parts.append('\n'.join(line for line in text.splitlines()
                               if not line.startswith(('from .', 'from __future__'))))
    script = header + '\n\n'.join(parts) + '\n'
    compile(script, name + '.py', 'exec')
    report = {
        'converter_version': '0.1.0', 'source': {'name': source.name, 'sha256': data['source_sha256']},
        'overrides': overrides or {}, 'parameters': {
            key: {'value': value['value'], 'unit': 'mm' if data['dimensions'][key] else '',
                  'expression': data['parameter_expressions'][key],
                  'update': 'rebuild' if key in data['rebuild_parameters'] else 'recompute'}
            for key, value in data['parameters'].items()},
        'capabilities': capabilities,
        'rebuild_parameters': data.get('rebuild_parameters', []),
        'validation': {'source': 'passed', 'python_compile': 'passed', 'fusion_runtime': 'not_run'},
    }
    manifest = {'autodeskProduct': 'Fusion', 'type': 'script', 'version': '0.1.0',
                'description': {'': 'Native model generated from ' + source.name},
                'supportedOS': 'windows|mac', 'editEnabled': True}
    readme = (
        '# ' + name + '\n\nFusion > Utilities > Scripts and Add-Ins > Scripts > + > select this folder > Run.\n\n'
        'Each run creates a new document. Edit linked dimensions in Modify > Change Parameters.\n'
        'Generation-time conditions, rotations/scales and unrecognized loops require regeneration from SCAD.\n'
        'Parameters marked rebuild also require regeneration for polyhedron geometry and Revolve placement/angle.\n'
        'See conversion-report.json for supported features and exact update limitations.\n'
        'Runtime evidence is written beside this script as native-report.json.\n')
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='.scad2fusion-', dir=output.parent) as temporary:
        staging = Path(temporary) / name
        staging.mkdir()
        (staging / (name + '.py')).write_text(script, encoding='utf-8')
        (staging / (name + '.manifest')).write_text(json.dumps(manifest, indent=2), encoding='utf-8')
        (staging / 'conversion-report.json').write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding='utf-8')
        (staging / 'README.md').write_text(readme, encoding='utf-8')
        staging.rename(output)
    return report
